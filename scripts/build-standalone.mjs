#!/usr/bin/env node
// Inlines src/*.mjs into one self-contained file at the repo root, so people
// can run it with `curl … | node` and never touch npm or git.
//
//   node scripts/build-standalone.mjs

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// Dependency order — ansi and sources first, cli last.
const ORDER = ['ansi', 'sources', 'download', 'banner', 'tokens', 'cli'];

const builtins = new Map(); // specifier -> local name(s)
const chunks = [];

for (const name of ORDER) {
  const src = await readFile(join(root, 'src', `${name}.mjs`), 'utf8');
  const kept = [];

  for (const line of src.split('\n')) {
    // Only line 1 of the bundle may carry a shebang; drop the sources' own.
    if (line.startsWith('#!')) continue;

    // Local imports vanish; their contents are inlined below.
    if (/^\s*import\s.*from\s+'\.\//.test(line)) continue;

    // Node builtins get hoisted to the top of the bundle, deduped.
    const m = line.match(/^\s*import\s+(.+?)\s+from\s+'(node:[^']+)';?\s*$/);
    if (m) {
      const [, spec, mod] = m;
      if (!builtins.has(mod)) builtins.set(mod, spec);
      else if (builtins.get(mod) !== spec) {
        throw new Error(`conflicting default import for ${mod}: "${builtins.get(mod)}" vs "${spec}"`);
      }
      continue;
    }

    // `export` is meaningless once everything shares one scope.
    kept.push(line.replace(/^export (const|let|function|class|async function) /, '$1 '));
  }

  chunks.push(
    `\n// ${'─'.repeat(66)}\n// src/${name}.mjs\n// ${'─'.repeat(66)}\n` +
    kept.join('\n').trimStart(),
  );
}

const header = [
  '#!/usr/bin/env node',
  '//',
  '// wallgrab — bulk wallpaper downloader. Single-file build.',
  '//',
  '// Generated by scripts/build-standalone.mjs from src/. Do not edit by hand;',
  '// change the sources and rebuild. Zero dependencies, Node 18+.',
  '//',
  '// Run it directly:   node wallgrab.mjs',
  '// Or pipe it:         curl -fsSL <raw-url>/wallgrab.mjs | node -',
  '//',
].join('\n');

const imports = [...builtins]
  .map(([mod, spec]) => `import ${spec} from '${mod}';`)
  .join('\n');

// Guard against two modules declaring the same top-level name.
const body = chunks.join('\n');
const decls = [...body.matchAll(/^(?:const|let|function|class) ([A-Za-z_$][\w$]*)/gm)]
  .map((m) => m[1]);
const dupes = decls.filter((d, i) => decls.indexOf(d) !== i);
if (dupes.length) {
  console.error(`\x1b[31m✖ name collisions in bundle: ${[...new Set(dupes)].join(', ')}\x1b[0m`);
  process.exit(1);
}

const out = `${header}\n${imports}\n${body}\n`;
await writeFile(join(root, 'wallgrab.mjs'), out);

const kb = (Buffer.byteLength(out) / 1024).toFixed(1);
console.log(`\x1b[32m✓\x1b[0m wallgrab.mjs  ${kb} kB  ${ORDER.length} modules inlined  ${decls.length} top-level names, 0 collisions`);
