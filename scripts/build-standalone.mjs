#!/usr/bin/env node
// Inlines src/*.mjs into one self-contained file at the repo root, so people
// can run it with `curl … | node` and never touch npm or git.
//
//   node scripts/build-standalone.mjs
//
// Two things a naive concatenation gets wrong, both handled here:
//   1. `import { width as sw }` — stripping the import loses the alias, so
//      `sw` becomes a ReferenceError at runtime. We re-emit aliases.
//   2. two modules declaring the same top-level name — would be a redeclare.

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// Dependency order — ansi and sources first, cli last (it self-executes).
const ORDER = ['ansi', 'sources', 'download', 'banner', 'tokens', 'cli'];

const builtins = new Map();      // 'node:path' -> 'join'
const aliasesFor = new Map();    // 'ansi' -> [{ alias: 'sw', original: 'width' }]

// ── pass 1: read everything, resolve imports ───────────────────────────
// Must be separate from emission: tokens.mjs aliases ansi.mjs, so ansi's
// aliases are not known until tokens has been read — but ansi is emitted first.
const sourcesText = new Map();
for (const name of ORDER) {
  sourcesText.set(name, await readFile(join(root, 'src', `${name}.mjs`), 'utf8'));
}

for (const [name, src] of sourcesText) {
  for (const line of src.split('\n')) {
    const bi = line.match(/^\s*import\s+(.+?)\s+from\s+'(node:[^']+)';?\s*$/);
    if (bi) {
      const [, spec, mod] = bi;
      if (!builtins.has(mod)) builtins.set(mod, spec);
      else if (builtins.get(mod) !== spec) {
        throw new Error(`conflicting default import for ${mod}: "${builtins.get(mod)}" vs "${spec}"`);
      }
      continue;
    }
    const li = line.match(/^\s*import\s+\{([^}]+)\}\s+from\s+'\.\/([\w.-]+)\.mjs';?\s*$/);
    if (li) {
      const [, names, from] = li;
      for (const part of names.split(',')) {
        const bits = part.trim().split(/\s+as\s+/);
        if (bits.length === 2) {
          if (!aliasesFor.has(from)) aliasesFor.set(from, []);
          aliasesFor.get(from).push({ alias: bits[1].trim(), original: bits[0].trim() });
        }
      }
    }
  }
}

// ── pass 2: emit each module, rebinding its aliases right after it ─────
const chunks = [];
for (const name of ORDER) {
  const src = sourcesText.get(name);
  const kept = [];

  for (const line of src.split('\n')) {
    // Only line 1 of the bundle may carry a shebang; drop the sources' own.
    if (line.startsWith('#!')) continue;
    // Imports are hoisted to the top or resolved as aliases below.
    if (/^\s*import\s.*from\s+'(node:|\.\.?\/)[^']*';?\s*$/.test(line)) continue;

    // `export` is meaningless once everything shares one scope.
    kept.push(line.replace(/^export (const|let|function|class|async function) /, '$1 '));
  }

  const aliases = (aliasesFor.get(name) || [])
    .map(({ alias, original }) => `const ${alias} = ${original};`)
    .join('\n');

  chunks.push(
    `\n// ${'─'.repeat(66)}\n// src/${name}.mjs\n// ${'─'.repeat(66)}\n` +
    kept.join('\n').trimStart() +
    (aliases ? `\n\n// import aliases re-bound by the bundler\n${aliases}\n` : ''),
  );
}

const header = [
  '#!/usr/bin/env node',
  '//',
  '// wallgrab — bulk wallpaper downloader. Single-file build.',
  '//',
  '// Generated by scripts/build-standalone.mjs from src/. Do not edit by hand;',
  '// change the sources and rebuild. Zero dependencies, Node 18+.',
  '//',
].join('\n');

const imports = [...builtins]
  .map(([mod, spec]) => `import ${spec} from '${mod}';`)
  .join('\n');

const body = chunks.join('\n');

// ── guard: duplicate top-level declarations ────────────────────────────
const decls = [...body.matchAll(/^(?:const|let|function|class) ([A-Za-z_$][\w$]*)/gm)]
  .map((m) => m[1]);
const dupes = [...new Set(decls.filter((d, i) => decls.indexOf(d) !== i))];
if (dupes.length) {
  console.error(`\x1b[31m✖ name collisions in bundle: ${dupes.join(', ')}\x1b[0m`);
  process.exit(1);
}

const out = `${header}\n${imports}\n${body}\n`;
await writeFile(join(root, 'wallgrab.mjs'), out);

const kb = (Buffer.byteLength(out) / 1024).toFixed(1);
const aliasCount = [...aliasesFor.values()].reduce((n, a) => n + a.length, 0);
console.log(
  `\x1b[32m✓\x1b[0m wallgrab.mjs  ${kb} kB  ${ORDER.length} modules inlined  ` +
  `${decls.length} top-level names, 0 collisions, ${aliasCount} alias(es) re-bound`,
);
